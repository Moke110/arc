#!/usr/bin/env Rscript
#
# Generate the pinned mouse -> human ortholog table for the Stage 2 gene-axis
# evidence product (ticket #183, spec section C).
#
# The repository has no axis-level mouse->human table. This script derives one
# deterministically from the two mouse MIRI DEG items with the pinned `arc`
# environment's homologene package (the same `mouse2human` definition used by the
# shared per-item ortholog helper in each disease item's `script/map_to_human.R`)
# and prints the pinned package versions. The
# table is then a tracked, digest-sealed input of the gene-axis build.
#
# Candidate policy (stage2 AGENTS.md acceptance and replacement; ADR 0062): the
# script never writes the accepted table directly. It writes
#   execution/gene_axis/mouse_human_orthologs.candidate.csv
# (candidates stay outside formal `output/`), computes the candidate's sha256,
# and compares it with the accepted table's sha256:
#   * identical  -> the accepted table is already the generated bytes; nothing
#                   is replaced and the candidate is removed;
#   * different  -> the script stops and keeps the candidate for review; pass
#                   `--args --accept` to deliberately replace the accepted table
#                   (the ledger in log/gene-axis/record.md and the build manifest
#                   must then be re-pinned).
#   * no accepted table -> the candidate is pinned in place.
#
# Run with the pinned `arc` R entry point (the env's `R` wrapper is mis-patched):
#   R_HOME=/home/chang/miniconda3/envs/arc/lib/R \
#     /home/chang/miniconda3/envs/arc/lib/R/bin/exec/R --no-save --slave \
#     --file=stage2/01_bases/execution/build_mouse_orthologs.R
# Deliberate replacement:
#   R_HOME=/home/chang/miniconda3/envs/arc/lib/R \
#     /home/chang/miniconda3/envs/arc/lib/R/bin/exec/R --no-save --slave \
#     --file=stage2/01_bases/execution/build_mouse_orthologs.R --args --accept

suppressPackageStartupMessages({
  library(homologene)
  library(org.Mm.eg.db)
})

args <- commandArgs(trailingOnly = TRUE)
accept <- '--accept' %in% args
unknown <- setdiff(args, '--accept')
if (length(unknown)) stop('unknown argument(s): ', paste(unknown, collapse = ', '))

find_repo_root <- function(start_dir) {
  dir <- normalizePath(start_dir, mustWork = TRUE)
  repeat {
    if (file.exists(file.path(dir, ".git"))) return(dir)
    parent <- dirname(dir)
    if (identical(parent, dir)) {
      stop("cannot find the repository root (no .git directory above ", start_dir, ")")
    }
    dir <- parent
  }
}

sha256_file <- function(path) {
  output <- system2("sha256sum", shQuote(path), stdout = TRUE, stderr = TRUE)
  if (!length(output) || nchar(output[1]) < 64) {
    stop("sha256sum did not return a digest for ", path)
  }
  substr(output[1], 1, 64)
}

script_arg <- grep("^--file=", commandArgs(), value = TRUE)
if (!length(script_arg)) stop("run this script with R --file=...")
SCRIPT_DIR <- dirname(normalizePath(sub("^--file=", "", script_arg[1])))
REPO_ROOT <- find_repo_root(SCRIPT_DIR)

mouse_sources <- c(
  file.path(REPO_ROOT, "disease_data/GSE160516/source/GSE160516_deg_results.csv"),
  file.path(REPO_ROOT, "disease_data/GSE108940/source/GSE108940_WT_deg_results.csv")
)
missing <- mouse_sources[!file.exists(mouse_sources)]
if (length(missing)) stop("missing mouse DEG source: ", paste(missing, collapse = ", "))

mouse_symbols <- unique(unlist(lapply(mouse_sources, function(path) {
  as.character(read.csv(path, stringsAsFactors = FALSE)$Gene)
})))
mouse_symbols <- sort(mouse_symbols)

mapped <- homologene::mouse2human(mouse_symbols)
table <- unique(data.frame(
  mouse_symbol = as.character(mapped$mouseGene),
  human_symbol = as.character(mapped$humanGene),
  stringsAsFactors = FALSE
))
table <- table[order(table$mouse_symbol, table$human_symbol), , drop = FALSE]
table <- table[table$mouse_symbol != "" & table$human_symbol != "", , drop = FALSE]

accepted <- file.path(REPO_ROOT,
                      "stage2/01_bases/output/gene-axis/mouse_human_orthologs.csv")
candidate_dir <- file.path(REPO_ROOT, "stage2/01_bases/execution/gene_axis")
candidate <- file.path(candidate_dir, "mouse_human_orthologs.candidate.csv")
dir.create(candidate_dir, recursive = TRUE, showWarnings = FALSE)
write.csv(table, candidate, row.names = FALSE, quote = FALSE)

candidate_digest <- sha256_file(candidate)
cat("mouse symbols:", length(mouse_symbols), "\n")
cat("mapping rows:", nrow(table), "\n")
cat("distinct mapped mouse symbols:", length(unique(table$mouse_symbol)), "\n")
cat("candidate:", candidate, "\n")
cat("candidate sha256:", candidate_digest, "\n")
cat("R:", R.version.string, "\n")
cat("homologene:", as.character(packageVersion("homologene")), "\n")
cat("org.Mm.eg.db:", as.character(packageVersion("org.Mm.eg.db")), "\n")

if (!file.exists(accepted)) {
  file.copy(candidate, accepted, overwrite = FALSE)
  unlink(candidate)
  cat("accepted table did not exist; pinned candidate as:", accepted, "\n")
  cat("accepted sha256:", sha256_file(accepted), "\n")
} else {
  accepted_digest <- sha256_file(accepted)
  cat("accepted:", accepted, "\n")
  cat("accepted sha256:", accepted_digest, "\n")
  if (identical(candidate_digest, accepted_digest)) {
    unlink(candidate)
    cat("candidate is byte-identical to the accepted table; accepted table unchanged\n")
  } else if (accept) {
    file.copy(candidate, accepted, overwrite = TRUE)
    unlink(candidate)
    cat("accepted table REPLACED (--accept); new sha256:", sha256_file(accepted), "\n")
  } else {
    stop("candidate sha256 differs from the accepted table; refusing to replace it.\n",
         "  candidate: ", candidate, "\n",
         "  review the candidate, then re-run with `--args --accept` to replace the ",
         "accepted table and re-pin the record/manifest")
  }
}
