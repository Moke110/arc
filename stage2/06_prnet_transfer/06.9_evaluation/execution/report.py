#!/usr/bin/env python
"""Render the first-round report section from the frozen record.

    python execution/report.py --record-dir output/record            # write results_section.md
    python execution/report.py --record-dir output/record --write-readme

The section is a pure function of ``summary.json`` plus the tracked tables; the README
results block between the generated markers is replaced, never hand-edited. A dry-run
record renders a clearly labelled harness section and refuses to touch the README.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Mapping

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

import common  # noqa: E402
from common import DEFAULT_OUT, EvaluationError, load_json, write_text_atomic  # noqa: E402

BEGIN_MARKER = "<!-- BEGIN RESULTS (generated by 06.9_evaluation/execution/report.py; do not edit) -->"
END_MARKER = "<!-- END RESULTS -->"


def _fmt(value: Any, digits: int = 4, signed: bool = False) -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "n/a"
    if number != number:  # NaN
        return "n/a"
    if signed:
        return f"{number:+.{digits}f}"
    return f"{number:.{digits}f}"


def _read(path: Path) -> pd.DataFrame:
    if not path.exists():
        return pd.DataFrame()
    frame = common.read_table(path)
    for column in frame.columns:
        if column in ("stratum_type", "stratum_value", "note"):
            continue
        converted = pd.to_numeric(frame[column], errors="coerce")
        if converted.notna().sum() == frame[column].notna().sum():
            frame[column] = converted
    return frame


def render(record_dir: Path | str) -> str:
    record_dir = Path(record_dir)
    summary = load_json(record_dir / "summary.json")
    phase = summary.get("phase", "?")
    dry_run = bool(summary.get("dry_run"))
    lines: list[str] = []
    if dry_run:
        lines += [
            "> **HARNESS DRY RUN — NOT A TEST RESULT.** This section was rendered from a",
            "> partial/validation run to validate the ticket-#9 aggregation path. It contains",
            "> no first-round test numbers and must never be quoted as one.",
            "",
        ]
    models = summary.get("models") or {}
    population = summary.get("test_population") or {}
    primary = summary.get("primary_bar") or {}
    questions = summary.get("questions") or {}
    strata = summary.get("strata") or {}
    budgets = summary.get("budgets") or {}
    bar = primary.get("auprc_200")

    lines += [
        f"### Evaluated population ({phase} role)",
        "",
        f"- {population.get('n_rows', 'n/a')} rows / "
        f"{population.get('n_conditions', 'n/a')} conditions / "
        f"{population.get('n_drugs', 'n/a')} drugs over "
        f"{population.get('n_folds', 'n/a')} folds"
        + (
            "; identical to #8's test population."
            if phase == "test"
            else " (validation role — harness dry run, not the test population)."
        ),
        f"- Metric: direction AUPRC@{summary.get('k', 200)} (macro over drug×dose conditions, "
        "replicates aggregated within a condition first); auxiliary Δ RMSE / Pearson / "
        "Spearman over the same conditions.",
        "",
        "### Headline test results by initialisation",
        "",
        "| init | AUPRC@200 (macro over folds) | per-fold (mean of 3 seeds) | up | down | Δ RMSE | Pearson | Spearman |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for init in ("random", "tahoe"):
        block = models.get(init) or {}
        per_fold = block.get("per_fold") or {}
        folds = " / ".join(
            _fmt((per_fold.get(str(fold)) or {}).get("auprc_200"), 4)
            for fold in sorted(int(key) for key in per_fold)
        )
        aux = block.get("auxiliary") or {}
        lines.append(
            f"| {init} | **{_fmt(block.get('macro_auprc_200_over_folds'))}** | {folds} | "
            f"{_fmt(block.get('macro_auprc_up_200_over_folds'))} | "
            f"{_fmt(block.get('macro_auprc_down_200_over_folds'))} | "
            f"{_fmt(aux.get('rmse'))} | {_fmt(aux.get('pcc'))} | {_fmt(aux.get('spearman'))} |"
        )
    if primary.get("bars"):
        lines += ["", "**Simple baselines on the identical test population (#8):**", "",
                  "| baseline | AUPRC@200 | up | down | Δ RMSE | Pearson | Spearman | role |",
                  "|---|---|---|---|---|---|---|---|"]
        for name, entry in primary["bars"].items():
            lines.append(
                f"| `{name}` | {_fmt(entry.get('auprc_200'))} | "
                f"{_fmt(entry.get('auprc_up_200'))} | {_fmt(entry.get('auprc_down_200'))} | "
                f"{_fmt(entry.get('rmse'))} | {_fmt(entry.get('pcc'))} | "
                f"{_fmt(entry.get('spearman'))} | {entry.get('role', '')} |"
            )
        if bar is not None:
            lines += ["", f"The primary bar is `delta_mean` = **{_fmt(bar)}** AUPRC@200."]

    lines += ["", "### Acceptance question (a): does Tahoe pretraining beat random init?", ""]
    q_a = questions.get("q_a_tahoe_vs_random") or {}
    overall = q_a.get("overall") or {}
    if overall.get("mean") is not None:
        lines += [
            f"- **Paired drug-level gain (Tahoe − random): {_fmt(overall.get('mean'), 4, True)}** "
            f"AUPRC@200, 95% bootstrap CI "
            f"[{_fmt(overall.get('ci_low'), 4, True)}, {_fmt(overall.get('ci_high'), 4, True)}], "
            f"n={overall.get('n')} drugs, B={overall.get('n_bootstrap')}, "
            f"seed={overall.get('seed')}.",
            f"- **Verdict (pre-registered rule): `{q_a.get('verdict')}`.**",
            f"- Seed stability (mean paired gain per seed): "
            + ", ".join(
                f"{seed}: {_fmt(value, 4, True)}"
                for seed, value in (q_a.get("per_seed_mean_gain") or {}).items()
            )
            + (
                f" (sd over seeds {_fmt(q_a.get('per_seed_gain_sd'))})."
                if q_a.get("per_seed_gain_sd") is not None
                else "."
            ),
            "",
            "| fold | mean paired gain over drugs |",
            "|---|---|",
        ]
        for fold, entry in (q_a.get(f"per_fold_{q_a.get('gain', 'gain_tahoe_minus_random')}") or {}).items():
            lines.append(f"| {fold} | {_fmt(entry.get('mean'), 4, True)} |")
    else:
        lines.append("- not computable from this (partial) record.")

    lines += ["", "### Acceptance question (b): does either init beat the simple baselines?", ""]
    for key, label in (
        ("q_b_tahoe_vs_primary_baseline", "Tahoe init − `delta_mean`"),
        ("q_b_random_vs_primary_baseline", "random init − `delta_mean`"),
    ):
        block = questions.get(key) or {}
        stats = block.get("overall") or {}
        if stats.get("mean") is None:
            continue
        lines.append(
            f"- **{label}: {_fmt(stats.get('mean'), 4, True)}** AUPRC@200 "
            f"(95% CI [{_fmt(stats.get('ci_low'), 4, True)}, "
            f"{_fmt(stats.get('ci_high'), 4, True)}], n={stats.get('n')} drugs) — "
            f"verdict `{block.get('verdict')}`."
        )
    constant = questions.get("q_constant_no_change") or {}
    if constant.get("tahoe_vs_no_change"):
        tahoe = (constant["tahoe_vs_no_change"].get("overall") or {})
        lines.append(
            f"- vs `no_change` (chance AUPRC = k/n_genes): Tahoe "
            f"{_fmt(tahoe.get('mean'), 4, True)}"
            f" (CI [{_fmt(tahoe.get('ci_low'), 4, True)}, "
            f"{_fmt(tahoe.get('ci_high'), 4, True)}])."
        )

    lines += ["", "### Strata", ""]
    strata_table = _read(record_dir / "strata.csv")
    if not strata_table.empty:
        lines += [
            "| stratum | value | n conditions | n drugs | random AUPRC@200 | Tahoe AUPRC@200 | Tahoe−random | 95% CI |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for _, row in strata_table.iterrows():
            lines.append(
                f"| {row['stratum_type']} | {row['stratum_value']} | {int(row['n_conditions'])} | "
                f"{int(row['n_drugs'])} | {_fmt(row.get('random_auprc_200'))} | "
                f"{_fmt(row.get('tahoe_auprc_200'))} | "
                f"{_fmt(row.get('gain_tahoe_minus_random'), 4, True)} | "
                f"[{_fmt(row.get('gain_tahoe_minus_random_ci_low'), 4, True)}, "
                f"{_fmt(row.get('gain_tahoe_minus_random_ci_high'), 4, True)}] |"
            )
        lines += [
            "",
            f"Low-response and toxicity labels are **unknown** on all "
            f"{strata.get('unknown_labels', {}).get('response_label', {}).get('n_conditions', 'n/a')} "
            "conditions: no per-well readout exists in this round and the labels are never "
            "inferred from transcriptomic magnitude (06.2 §6).",
        ]
        seen_rows = strata_table[strata_table["stratum_type"] == "tahoe_seen"]
        if not seen_rows.empty:
            values = {
                str(row["stratum_value"]): (int(row["n_drugs"]), int(row["n_conditions"]))
                for _, row in seen_rows.iterrows()
            }
            seen = values.get("True", (0, 0))
            unseen = values.get("False", (0, 0))
            lines.append(
                f"Tahoe-seen strata: {seen[0]} of the test drugs ({seen[1]} conditions) have a "
                f"drug key observed in Tahoe treated rows; {unseen[0]} drugs "
                f"({unseen[1]} conditions) were never observed there. "
                f"({strata.get('tahoe_seen', {}).get('n_tahoe_seen_drug_keys', 'n/a')} drug "
                "keys are observed in Tahoe treated rows overall.)"
            )
        lines += [
        ]
    else:
        lines.append("- no strata table in this record.")

    evaluation = budgets.get("evaluation") or {}
    training = budgets.get("training") or {}
    lines += [
        "",
        "### Actual budgets and failures",
        "",
        f"- Evaluation: {evaluation.get('units_completed', 'n/a')}/"
        f"{evaluation.get('units_planned', 'n/a')} units completed, "
        f"**{evaluation.get('units_failed', 0)} failed**; wall "
        f"{_fmt(evaluation.get('wall_s_total'), 1)} s total, per-unit mean "
        f"{_fmt((evaluation.get('wall_s_per_unit') or {}).get('mean'), 1)} s; host peak "
        f"{_fmt(evaluation.get('host_peak_rss_mb'), 0)} MiB; GPU peak "
        f"{evaluation.get('gpu_peak_mb', 'n/a')} MiB; repeated inference byte-identical "
        "(predict.py runs it twice).",
    ]
    for init, block in training.items():
        epochs = block.get("epochs_run") or {}
        lines.append(
            f"- {init} training budget of the evaluated checkpoints: epochs "
            f"{_fmt(epochs.get('min'), 0)}/{_fmt(epochs.get('mean'), 1)}/"
            f"{_fmt(epochs.get('max'), 0)} (min/mean/max), "
            f"capped={block.get('capped_units', 'n/a')}, stop reasons "
            f"`{block.get('stop_reasons', {})}`."
        )

    identity = summary.get("units_manifest") or {}
    deviations = summary.get("deviations") or []
    lines += [
        "",
        "### Input and model identity",
        "",
        f"- units manifest: `{common.relpath(identity.get('path') or '')}` sha256 "
        f"`{str(identity.get('sha256'))[:16]}…` (created {identity.get('created_utc')}, "
        f"{identity.get('n_scored')}/{identity.get('n_units')} units scored).",
        f"- frozen data identity: `{summary.get('data_identity')}` (manifest sha256 "
        f"`{str(summary.get('frozen_manifest_sha256'))[:16]}…`).",
        f"- every checkpoint sha256 and config digest re-verified against #6/#7's "
        "`selected_checkpoints.csv` before scoring; model cards in "
        "`output/model_cards/`.",
        "",
        *(
            ["### Recorded deviations", ""]
            + [
                f"- `{dev.get('id')}` ({dev.get('component')}, fix `{dev.get('fix_commit')}`): "
                f"{dev.get('what')} Units: {', '.join(dev.get('unit_ids') or [])}. "
                f"Effect on results: {dev.get('effect_on_results')}; {dev.get('recovery')}."
                for dev in deviations
            ]
            + [""]
            if deviations
            else []
        ),
        "### Scope, negative-result clause and decision rule",
        "",
        f"- **Scope.** {summary.get('scope_statement', '')}",
        f"- **Negative-result clause.** {summary.get('negative_result_clause', '')}",
        f"- **Decision rule.** {summary.get('decision_rule', '')}",
        "",
        "### Reproduce",
        "",
        "```bash",
        "cd stage2/06_prnet_transfer/06.9_evaluation/execution",
        "make units            # verify the 30 frozen selections (checkpoint sha256/config/identity)",
        "make score-test       # predict + evaluate all 30 units (test phase, explicit confirmation)",
        "make record           # tables + summary + gates  -> output/record",
        "make cards            # 30 model cards            -> output/model_cards",
        "make report           # regenerate this section + figures",
        "make check            # re-derive the record byte-for-byte",
        "```",
    ]
    return "\n".join(lines) + "\n"


def splice_readme(readme: Path, section: str) -> bool:
    text = readme.read_text(encoding="utf-8")
    if BEGIN_MARKER not in text or END_MARKER not in text:
        raise EvaluationError(
            f"{readme}: generated-results markers not found; add\n{BEGIN_MARKER}\n{END_MARKER}"
        )
    head, _, remainder = text.partition(BEGIN_MARKER)
    _, _, tail = remainder.partition(END_MARKER)
    updated = f"{head}{BEGIN_MARKER}\n{section.rstrip()}\n{END_MARKER}{tail}"
    if updated == text:
        return False
    write_text_atomic(readme, updated)
    return True


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Render the ticket-#9 report section from the frozen record.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--record-dir", type=Path, default=DEFAULT_OUT / "record")
    parser.add_argument("--readme", type=Path, default=None,
                        help="default: this substep's README.md")
    parser.add_argument("--write-readme", action="store_true")
    return parser


def main(argv: list[str] | None = None) -> int:
    ns = build_parser().parse_args(argv)
    record_dir = Path(ns.record_dir)
    if not (record_dir / "summary.json").exists():
        print(f"error: no summary.json in {record_dir}", file=sys.stderr)
        return 2
    summary = load_json(record_dir / "summary.json")
    section = render(record_dir)
    write_text_atomic(record_dir / "results_section.md", section)
    print(f"wrote {record_dir / 'results_section.md'} ({len(section)} chars)")
    if ns.write_readme:
        if summary.get("dry_run"):
            print(
                "error: refusing to write the README from a dry-run record",
                file=sys.stderr,
            )
            return 3
        readme = Path(ns.readme) if ns.readme is not None else common.EVAL_DIR / "README.md"
        changed = splice_readme(readme, section)
        print(f"{'updated' if changed else 'unchanged'}: {readme}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
