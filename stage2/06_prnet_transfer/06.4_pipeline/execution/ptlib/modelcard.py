def _fmt(value: Any, spec: str = ".6f") -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "n/a"
    if not math.isfinite(number):
        return "n/a"
    return format(number, spec)


def _sha(record: Mapping[str, Any] | None, key: str = "sha256", n: int = 16) -> str:
    if not isinstance(record, Mapping):
        return "n/a"
    value = record.get(key)
    if not isinstance(value, str):
        return "n/a"
    return value[:n] + "…"


def _ini(manifest: Mapping[str, Any]) -> dict[str, Any]:
    init = manifest.get("init") or {}
    return dict(init) if isinstance(init, Mapping) else {}


def render_model_card(
    run_dir: Path,
    manifest: Mapping[str, Any],
    config: Mapping[str, Any],
    history: Mapping[str, Any],
    evaluation: Mapping[str, Any] | None = None,
) -> str:
    stage = manifest.get("stage", "?")
    run = config.get("run", {})
    recipe = config.get("recipe", {})
    struct = config.get("structure", {})
    metric = config.get("metric", {})
    k = metric.get("k", "?")
    entries = list(history.get("history", []))
    first = entries[0] if entries else {}
    last = entries[-1] if entries else {}
    best_epoch = manifest.get("best_epoch")
    best_entry = next((e for e in entries if e.get("epoch") == best_epoch), {})
    init = _ini(manifest)
    smoke = bool(manifest.get("smoke"))
    status = (
        "**Pipeline smoke run — NOT a science result.** "
        "This run exists only to prove the path executes end to end."
        if smoke
        else "**Pipeline training unit** — a run record; see the owning ticket for the "
        "study claim."
    )
    checkpoint = manifest.get("checkpoint") or {}
    timings = manifest.get("timings") or {}
    data = manifest.get("data") or {}
    axis = (data.get("gene_axis") or {}) if isinstance(data, Mapping) else {}

    lines = [
        f"# PRnet {stage} — model card",
        "",
        "Auto-generated by `stage2/06_prnet_transfer/06.4_pipeline/execution/"
        "make_model_card.py` from the run's `manifest.json` / `config.json` / "
        "`fit_history.json`.",
        "",
        f"- **Status:** {status}",
        f"- **Run directory:** `{run_dir}`",
        f"- **Created:** {manifest.get('created_utc', 'n/a')}",
        f"- **Command:** `{' '.join(manifest.get('command') or [])}`",
        f"- **Git:** `{(manifest.get('git') or {}).get('sha')}` "
        f"branch `{(manifest.get('git') or {}).get('branch')}` "
        f"dirty `{(manifest.get('git') or {}).get('dirty')}`",
        "",
        "## Data identity",
        "",
        f"- frozen input: `{data.get('dir', 'n/a')}`",
        f"- gene axis: {axis.get('n_genes', 'n/a')} genes "
        f"({axis.get('measured', 'n/a')} measured)",
        f"- locked config sha256: `{_sha((data.get('locked_config') or {}), 'sha256')}`",
        f"- data artifacts (sha256, first 16): "
        + ", ".join(
            f"`{name}` {digest[:8]}…"
            for name, digest in sorted((data.get("artifacts") or {}).items())
        ),
        f"- rows: {run.get('data_counts')}",
        "",
        "## Model",
        "",
        f"- structure: hidden {struct.get('hidden')}, state latent {struct.get('z_dim')}, "
        f"drug latent {struct.get('c_dim')}, noise {struct.get('n_dim')}, "
        f"drug input {struct.get('drug_dim')} (rFCFP4), genes {struct.get('n_genes')}",
        f"- initialisation: **{init.get('mode', 'n/a')}**"
        + (
            f" — warm start from `{init.get('source_path')}` "
            f"(sha256 `{str(init.get('checkpoint_sha256'))[:16]}…`, "
            f"epoch {init.get('checkpoint_epoch')}, seed {init.get('checkpoint_seed')})"
            if init.get("mode") == "pretrained"
            else f" — author default normal_(0, 0.02) with seed {manifest.get('seed')}"
        ),
        f"- parameter count: {init.get('parameter_count', 'n/a')}",
        f"- checkpoint: `{checkpoint.get('path')}` sha256 "
        f"`{str(checkpoint.get('sha256'))[:16]}…`, epoch {checkpoint.get('best_epoch')}, "
        f"strict reload identical: {checkpoint.get('reload_identical')}",
        "",
        "## Recipe",
        "",
        f"- loss: Gaussian NLL (`GUSS`; may be negative, never clamped)",
        f"- optimizer: Adam(lr={recipe.get('lr')}, weight_decay={recipe.get('weight_decay')})",
        f"- scheduler: ReduceLROnPlateau(mode=**max**, factor={recipe.get('sched_factor')}, "
        f"patience={recipe.get('sched_patience')}, min_lr={recipe.get('min_lr')}) "
        f"stepped on validation direction AUPRC@{k}",
        f"- batch {recipe.get('batch_size')}, max_epochs {recipe.get('max_epochs')}, "
        f"min_epochs {recipe.get('min_epochs')}, early-stop patience "
        f"{recipe.get('early_stop_patience')}",
        f"- selection metric: direction AUPRC@{k} (**max**); the test split never "
        "informs LR, epoch, seed or checkpoint choice",
        f"- seed {manifest.get('seed')}, device "
        f"{(manifest.get('device') or {}).get('resolved')} "
        f"({(manifest.get('device') or {}).get('name')})",
        f"- noise policy: {(manifest.get('noise_policy') or {}).get('train')}; "
        f"validation/inference: zero noise",
        "",
        "## Result",
        "",
        f"- epochs run: {manifest.get('epochs_run')}",
        f"- stop reason: `{manifest.get('stop_reason')}`",
        f"- best epoch {best_epoch}: validation AUPRC@{k} = "
        f"{_fmt(manifest.get('best_valid_auprc'))}",
    ]
    if first and last:
        lines += [
            f"- first epoch: train NLL {_fmt(first.get('train_loss'))} / "
            f"valid NLL {_fmt(first.get('valid_loss'))} / "
            f"valid AUPRC@{k} {_fmt(first.get('valid_auprc'))}",
            f"- last epoch: train NLL {_fmt(last.get('train_loss'))} / "
            f"valid NLL {_fmt(last.get('valid_loss'))} / "
            f"valid AUPRC@{k} {_fmt(last.get('valid_auprc'))}",
        ]
    per_epoch = timings.get("per_epoch_valid_s") or []
    gather = timings.get("per_epoch_valid_gather_s") or []
    forward = timings.get("per_epoch_valid_forward_s") or []
    ap = timings.get("per_epoch_valid_metrics_s") or []
    if per_epoch:
        lines += [
            "",
            "## Timing / resources",
            "",
            f"- wall time: {_fmt(timings.get('wall_s'), '.1f')} s",
            f"- train loop: {_fmt(timings.get('train_loop_s'), '.1f')} s",
            f"- per-epoch validation total: {_fmt(sum(per_epoch), '.2f')} s over "
            f"{len(per_epoch)} epochs (mean {_fmt(sum(per_epoch) / len(per_epoch), '.2f')} s)",
            f"- validation cost split, mean per epoch: gather "
            f"{_fmt(sum(gather) / len(gather), '.2f')} s / forward "
            f"{_fmt(sum(forward) / len(forward), '.2f')} s / AUPRC "
            f"{_fmt(sum(ap) / len(ap), '.2f')} s",
            f"- peak host RSS: {_fmt(manifest.get('peak_rss_mb'), '.0f')} MiB",
        ]
    cache = manifest.get("tahoe_cache") or {}
    if cache:
        lines += [
            "",
            "## Tahoe data path",
            "",
            f"- mode: `{cache.get('mode')}`"
            + (f", path `{cache.get('path')}`" if cache.get("path") else ""),
        ]
        if cache.get("layer_sha256"):
            lines.append(
                f"- derived cache full-array sha256: `{str(cache.get('layer_sha256'))[:16]}…` "
                f"(source sha256 `{str(cache.get('source_sha256'))[:16]}…`, "
                f"sample max|diff|={cache.get('sample_max_abs_diff')})"
            )
    if evaluation:
        lines += [
            "",
            "## Evaluation",
            "",
            f"- stage/role/fold: {evaluation.get('stage')}/"
            f"{evaluation.get('role')}/{evaluation.get('fold')}",
            f"- rows: {evaluation.get('n_rows')}, conditions: "
            f"{evaluation.get('n_conditions')}",
        ]
        headline = str(evaluation.get("headline_k"))
        macro = ((evaluation.get("by_k") or {}).get(headline) or {}).get("macro") or {}
        lines.append(
            f"- headline macro direction AUPRC@{headline}: "
            f"{_fmt(macro.get('mean'))} (sd {_fmt(macro.get('sd'))}, "
            f"nan {macro.get('nan')})"
        )
        reg = evaluation.get("regression") or {}
        lines.append(
            "- auxiliary Δ regression (macro over conditions): "
            f"RMSE {_fmt((reg.get('rmse') or {}).get('mean'))}, "
            f"Pearson {_fmt((reg.get('pcc') or {}).get('mean'))}, "
            f"Spearman {_fmt((reg.get('spearman') or {}).get('mean'))}"
        )
    lines += [
        "",
        "## Deviations (D0–D3)",
        "",
        "| id | deviation | why |",
        "|---|---|---|",
    ]
    for dev_id, deviation, why in DEV_RECORD:
        lines.append(f"| {dev_id} | {deviation} | {why} |")
    lines += [
        "",
        "## Caveats",
        "",
        "- A smoke run is a pipeline check only: small row subset, 2 epochs, no "
        "scientific interpretation. Per-epoch AUPRC@k is a validation number and",
        "  is not a test result.",
        "- Validation AUPRC@k uses top/bottom-k ranking labels from the condition-mean "
        "true Δ; it is not a significance test for differential expression.",
        "- The CM claim is about general iPSC-CM responses on the fixed consensus "
        "background; no donor/batch-specific or hypoxia/reoxygenation claim is made.",
        "",
    ]
    return "\n".join(lines)


def write_model_card(
    run_dir: Path | str,
    eval_dir: Path | str | None = None,
    out_path: Path | str | None = None,
) -> Path:
    run_dir = Path(run_dir)
    manifest_file = run_dir / "manifest.json"
    if not manifest_file.exists():
        raise SystemExit(f"no run manifest to build a model card from: {manifest_file}")
    manifest = manifest_mod.read_json(manifest_file)
    config = manifest_mod.read_json(run_dir / "config.json") if (run_dir / "config.json").exists() else {}
    history_file = run_dir / "fit_history.json"
    history = manifest_mod.read_json(history_file) if history_file.exists() else {"history": []}
    evaluation = None
    if eval_dir is not None:
        aggregate = Path(eval_dir) / "aggregate.json"
        if not aggregate.exists():
            raise SystemExit(f"evaluation directory has no aggregate.json: {aggregate}")
        evaluation = manifest_mod.read_json(aggregate)
    text = render_model_card(run_dir, manifest, config, history, evaluation)
    target = Path(out_path) if out_path is not None else run_dir / "model_card.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    return target
