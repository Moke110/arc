"""Model card generation for a run directory (and its optional evaluation).

The card is the human-facing run record: what was trained, on which frozen
artifacts (hashes), with which structure/recipe/seed/initialisation, the
per-epoch validation curve summary including the validation cost split
(gather / forward / AUPRC), checkpoint identity, measured wall time and peak RSS,
the stop reason, and the deviations that apply.  A smoke run is labelled as a
pipeline check, never as a science result.

Reads only the run's own artifacts (``manifest.json``, ``config.json``,
``fit_history.json``) and, when given, an evaluation directory's
``aggregate.json`` / ``per_condition.csv``.
"""

from __future__ import annotations

