#!/usr/bin/env python3
"""
Step 02 — Drug embeddings (v2, HG-aligned).

Verifies the frozen drug feature inputs and generates the HG biological
embeddings for the workflow via **author-pinned frozen inference**:

  input/                                  (static, never regenerated here)
  ├── all_drugs_unimol_arr.npy            # frozen UniMol features (11104 x 122 x 514)
  └── all_drugs_idx2smi.npy               # frozen idx -> SMILES mapping
  02_drug_embeddings/output/
  ├── DDS_edge_index_fda_tanimoto.npy     # FDA DDS edges, Tanimoto > 0.5 (v2-owned)
  ├── pins_layerwise.npz                  # per-layer L1000/gene pin states
  └── all_drugs_idx2HG.npy                # HG embeddings (11104 x 256)

The table is generated by the HG-aligned hybrid (docs/adr/0006): rows 0-8980 are
the author reference (byte-identical, by construction), rows 8981-11103 are
author-pinned FDA states aligned to the author-embedding scale. The step is
idempotent: an intact output table that passes all gates is reused; pass
--force to regenerate.

Usage:
    python 02_drug_embeddings/02_drug_embeddings.py            # idempotent
    python 02_drug_embeddings/02_drug_embeddings.py --force    # regenerate
"""

import argparse
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "_lib"))
from utils import WORKFLOW_ROOT  # noqa: E402

STEP_DIR = WORKFLOW_ROOT / "02_drug_embeddings"
INPUT_DIR = WORKFLOW_ROOT / "input"
OUTPUT_DIR = STEP_DIR / "output"
UNIMOL_ARR = "all_drugs_unimol_arr.npy"
SMI_MAPPING = "all_drugs_idx2smi.npy"
HG_EMBEDDINGS = "all_drugs_idx2HG.npy"
DDS_ARTIFACT = "DDS_edge_index_fda_tanimoto.npy"
N_DRUGS_EXPECTED = 11104


def _drug_count(arr) -> int:
    if getattr(arr, "ndim", 0) == 0 and arr.dtype == object:
        return len(arr.item())
    if hasattr(arr, "shape") and arr.ndim:
        return arr.shape[0]
    return len(arr)


def intact_hg_table() -> bool:
    path = OUTPUT_DIR / HG_EMBEDDINGS
    if not path.exists():
        return False
    try:
        arr = np.load(path, mmap_mode="r")
        ok = arr.shape[0] == N_DRUGS_EXPECTED and arr.shape[1] == 256
        del arr
        return ok
    except Exception:
        return False


def gates_pass() -> bool:
    cmd = [sys.executable, str(WORKFLOW_ROOT / "_lib" / "verify_gates.py")]
    return subprocess.run(cmd, cwd=WORKFLOW_ROOT).returncode == 0


def compute_dds() -> None:
    print(f"Cached FDA DDS artifact missing: {OUTPUT_DIR / DDS_ARTIFACT}")
    cmd = [sys.executable, str(STEP_DIR / "compute_dds_fda_tanimoto.py")]
    print(f"Running DDS recompute:\n  {' '.join(cmd)}")
    subprocess.run(cmd, cwd=WORKFLOW_ROOT, check=True)


def run_hg_inference(device: str, force: bool) -> bool:
    """Generate all_drugs_idx2HG.npy via author-pinned frozen inference.

    Returns True if a fresh table was generated, False if an intact cached
    table (passing all gates) was reused.
    """
    if not force and intact_hg_table():
        if gates_pass():
            print(f"Cached HG embeddings intact + gates pass: "
                  f"{OUTPUT_DIR / HG_EMBEDDINGS} — skipping inference")
            return False
        print(f"Cached HG embeddings present but gates fail — regenerating")

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    if not (OUTPUT_DIR / DDS_ARTIFACT).exists():
        compute_dds()

    cmd = [sys.executable, str(STEP_DIR / "hg_aligned_infer.py"),
           "--device", device]
    print(f"Running HG-aligned inference:\n  {' '.join(cmd)}")
    subprocess.run(cmd, cwd=WORKFLOW_ROOT, check=True)
    print(f"Wrote {OUTPUT_DIR / HG_EMBEDDINGS}")
    return True


def main():
    parser = argparse.ArgumentParser(description="Verify frozen embeddings + generate HG embeddings")
    parser.add_argument("--force", action="store_true",
                        help="Regenerate HG embeddings even if an intact table exists")
    parser.add_argument("--device", default="cuda:0", help="Device for HG inference")
    parser.add_argument("--skip-gates", action="store_true",
                        help="Do not run the gate harness after inference")
    args = parser.parse_args()

    # 1. Verify the static inputs (large gitignored artifacts, not committed).
    for name in (UNIMOL_ARR, SMI_MAPPING):
        path = INPUT_DIR / name
        if not path.exists():
            print(f"ERROR: missing static input {path}")
            print("The frozen UniMol array / SMILES mapping are large gitignored "
                  "artifacts and cannot be committed. Provision them (e.g. copy "
                  "from a prior checkout) before running the workflow.")
            sys.exit(1)
        try:
            arr = np.load(path, mmap_mode="r", allow_pickle=True)
        except ValueError:
            arr = np.load(path, allow_pickle=True)
        n = _drug_count(arr)
        if n != N_DRUGS_EXPECTED:
            print(f"ERROR: {name} has {n} drugs, expected {N_DRUGS_EXPECTED}")
            sys.exit(1)
        print(f"Static input present: {path} ({n} drugs)")

    # 2. HG embeddings (idempotent).
    generated = run_hg_inference(args.device, args.force)

    # 3. Gate harness (the verification seam). Reused cached tables already
    #    passed the gates inside run_hg_inference; fresh tables need them now.
    if not args.skip_gates and generated:
        print("\nRunning the gate harness...")
        if not gates_pass():
            print("\nERROR: one or more gates failed — see output above.")
            sys.exit(1)
        print("Gate harness passed.")

    for path in (INPUT_DIR / UNIMOL_ARR, INPUT_DIR / SMI_MAPPING,
                 OUTPUT_DIR / HG_EMBEDDINGS):
        arr = np.load(path, allow_pickle=True)
        print(f"  {path.name}: {_drug_count(arr)} drugs")


if __name__ == "__main__":
    main()
