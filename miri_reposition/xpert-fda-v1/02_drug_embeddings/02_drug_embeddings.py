#!/usr/bin/env python3
"""
Step 02 — Drug embeddings.

Verifies the frozen drug feature inputs and generates the HG biological
embeddings for the workflow:

  input/                                  (static, never regenerated here)
  ├── all_drugs_unimol_arr.npy            # frozen UniMol 3D features (11104 x 122 x 514)
  └── all_drugs_idx2smi.npy               # frozen idx -> SMILES mapping
  02_drug_embeddings/output/
  └── all_drugs_idx2HG.npy                # HG biological embeddings (11104 x 256)

The HG table is generated by HG inference and is idempotent: if an intact
output/all_drugs_idx2HG.npy already exists, the step skips inference and
reports the cached artifact. Pass --force to regenerate.

Usage:
    python 02_drug_embeddings/02_drug_embeddings.py            # idempotent
    python 02_drug_embeddings/02_drug_embeddings.py --force    # regenerate HG embeddings
"""

import argparse
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "_lib"))
from utils import WORKFLOW_ROOT, HG_ROOT  # noqa: E402

STEP_DIR = WORKFLOW_ROOT / "02_drug_embeddings"
INPUT_DIR = WORKFLOW_ROOT / "input"
OUTPUT_DIR = STEP_DIR / "output"
UNIMOL_ARR = "all_drugs_unimol_arr.npy"
SMI_MAPPING = "all_drugs_idx2smi.npy"
HG_EMBEDDINGS = "all_drugs_idx2HG.npy"
N_DRUGS_EXPECTED = 11104


def _drug_count(arr) -> int:
    if getattr(arr, "ndim", 0) == 0 and arr.dtype == object:
        return len(arr.item())
    if hasattr(arr, "shape") and arr.ndim:
        return arr.shape[0]
    return len(arr)


def intact_hg_table() -> bool:
    path = OUTPUT_DIR / HG_EMBEDDINGS
    if not path.exists():
        return False
    try:
        arr = np.load(path, mmap_mode="r")
        ok = arr.shape[0] == N_DRUGS_EXPECTED
        del arr
        return ok
    except Exception:
        return False


def run_hg_inference(device: str, force: bool) -> None:
    """Regenerate all_drugs_idx2HG.npy by fine-tuning HG on the extended graph.

    Per ADR-0002 the workflow owns its artifacts: HG is invoked here with the
    step's output path as the explicit output target, and the resulting table
    is a workflow artifact (the HG component itself never writes into a
    workflow directory on its own).
    """
    if not force and intact_hg_table():
        print(f"Cached HG embeddings intact: {OUTPUT_DIR / HG_EMBEDDINGS} — skipping inference")
        return

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    cmd = [
        sys.executable, "-m", "src.finetune_hg",
        "--device", device,
        "--lr", "5e-5", "--epochs", "50",
        "--update-xpert-embeddings",
        "--embeddings-output", str(OUTPUT_DIR / HG_EMBEDDINGS),
    ]
    print(f"Running HG fine-tune:\n  {' '.join(cmd)}")
    subprocess.run(cmd, cwd=HG_ROOT, check=True)
    print(f"Wrote {OUTPUT_DIR / HG_EMBEDDINGS}")


def main():
    parser = argparse.ArgumentParser(description="Verify frozen embeddings + generate HG embeddings")
    parser.add_argument("--force", action="store_true",
                        help="Regenerate HG embeddings even if an intact table exists")
    parser.add_argument("--device", default="cuda:0", help="Device for HG inference")
    args = parser.parse_args()

    # 1. Verify the static inputs (must already exist — large gitignored
    #    artifacts, not committed). Fail loudly at this step rather than
    #    mid-pipeline.
    for name in (UNIMOL_ARR, SMI_MAPPING):
        path = INPUT_DIR / name
        if not path.exists():
            print(f"ERROR: missing static input {path}")
            print("The frozen UniMol array / SMILES mapping are large gitignored "
                  "artifacts and cannot be committed. Provision them (e.g. copy "
                  "from a prior checkout, or regenerate the UniMol array with "
                  "unimol_tools) before running the workflow.")
            sys.exit(1)
        try:
            arr = np.load(path, mmap_mode="r", allow_pickle=True)
        except ValueError:
            arr = np.load(path, allow_pickle=True)
        n = _drug_count(arr)
        if n != N_DRUGS_EXPECTED:
            print(f"ERROR: {name} has {n} drugs, expected {N_DRUGS_EXPECTED}")
            sys.exit(1)
        print(f"Static input present: {path} ({n} drugs)")

    # 2. HG embeddings (idempotent).
    if args.force or not intact_hg_table():
        run_hg_inference(args.device, force=True)
    else:
        print(f"Cached HG embeddings intact: {OUTPUT_DIR / HG_EMBEDDINGS} — skipping inference")

    for path in (INPUT_DIR / UNIMOL_ARR, INPUT_DIR / SMI_MAPPING, OUTPUT_DIR / HG_EMBEDDINGS):
        arr = np.load(path, allow_pickle=True)
        print(f"  {path.name}: {_drug_count(arr)} drugs")


if __name__ == "__main__":
    main()
