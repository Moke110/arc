#!/usr/bin/env python3
"""
Stage 02 — Drug embeddings.

Arranges the frozen drug feature inputs and generates the HG biological
embeddings for the workflow:

  data/embeddings/
  ├── all_drugs_unimol_arr.npy   # frozen UniMol 3D features (11104 x 122 x 514)
  ├── all_drugs_idx2smi.npy      # frozen idx -> SMILES mapping
  └── all_drugs_idx2HG.npy       # HG biological embeddings (11104 x 256)

The UniMol array and SMILES mapping are static inputs and are never
regenerated here. The HG table is generated by HG inference and is idempotent:
if an intact data/embeddings/all_drugs_idx2HG.npy already exists, the stage
skips inference and reports the cached artifact. Pass --force to regenerate.

Usage:
    python scripts/02_drug_embeddings.py            # idempotent
    python scripts/02_drug_embeddings.py --force    # regenerate HG embeddings
"""

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from utils import WORKFLOW_ROOT, HG_ROOT  # noqa: E402

EMBEDDINGS_DIR = WORKFLOW_ROOT / "data" / "embeddings"
UNIMOL_ARR = "all_drugs_unimol_arr.npy"
SMI_MAPPING = "all_drugs_idx2smi.npy"
HG_EMBEDDINGS = "all_drugs_idx2HG.npy"
N_DRUGS_EXPECTED = 11104


def intact_hg_table() -> bool:
    path = EMBEDDINGS_DIR / HG_EMBEDDINGS
    if not path.exists():
        return False
    try:
        arr = np.load(path, mmap_mode="r")
        ok = arr.shape[0] == N_DRUGS_EXPECTED
        del arr
        return ok
    except Exception:
        return False


def run_hg_inference(device: str, force: bool) -> None:
    """Run HG fine-tune + inference to regenerate all_drugs_idx2HG.npy."""
    if not force and intact_hg_table():
        print(f"Cached HG embeddings intact: {EMBEDDINGS_DIR / HG_EMBEDDINGS} — skipping inference")
        return

    EMBEDDINGS_DIR.mkdir(parents=True, exist_ok=True)
    # Fine-tune HG on the extended FDA graph and write the all-drug table
    # directly into the workflow's embeddings dir.
    cmd = [
        sys.executable, "-m", "src.finetune_hg",
        "--device", device,
        "--lr", "5e-5", "--epochs", "50",
        "--update-xpert-embeddings",
        "--embeddings-output", str(EMBEDDINGS_DIR / HG_EMBEDDINGS),
    ]
    print(f"Running HG fine-tune:\n  {' '.join(cmd)}")
    subprocess.run(cmd, cwd=HG_ROOT, check=True)
    print(f"Wrote {EMBEDDINGS_DIR / HG_EMBEDDINGS}")


def main():
    parser = argparse.ArgumentParser(description="Arrange frozen embeddings + generate HG embeddings")
    parser.add_argument("--force", action="store_true",
                        help="Regenerate HG embeddings even if an intact table exists")
    parser.add_argument("--device", default="cuda:0", help="Device for HG inference")
    args = parser.parse_args()

    # 1. Freeze static inputs (must already exist — copied at workflow setup).
    for name in (UNIMOL_ARR, SMI_MAPPING):
        path = EMBEDDINGS_DIR / name
        if not path.exists():
            print(f"ERROR: missing static input {path}")
            print("Re-run the workflow setup or copy from the frozen snapshot.")
            sys.exit(1)
        print(f"Static input present: {path}")

    # 2. HG embeddings (idempotent).
    if args.force or not intact_hg_table():
        run_hg_inference(args.device, force=True)
    else:
        print(f"Cached HG embeddings intact: {EMBEDDINGS_DIR / HG_EMBEDDINGS} — skipping inference")

    for name in (UNIMOL_ARR, SMI_MAPPING, HG_EMBEDDINGS):
        arr = np.load(EMBEDDINGS_DIR / name, allow_pickle=True)
        shape = arr.shape[0] if hasattr(arr, "shape") and arr.ndim else len(arr)
        print(f"  {name}: {shape} drugs")


if __name__ == "__main__":
    main()
