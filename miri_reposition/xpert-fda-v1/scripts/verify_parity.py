#!/usr/bin/env python3
"""
Parity verification for the xpert-fda-v1 refactor.

The single testing seam of the workspace refactor (docs/adr/0004) is a parity
run: the refactored pipeline must reproduce the pre-refactor pipeline's scoring
logic on identical inputs. This script asserts that equality.

Checks:
  1. Stage 07 regenerates the reference gene sets byte-identically
     (union gene set + ranked reference vs the frozen snapshot's copies).
  2. The workflow scoring module reproduces the frozen scoring scripts
     (WCS+RGES, Zhang, pathway RGES) exactly on the same DEG input.
  3. The z-scored DEG produced by stage 06 equals per-gene z-scoring of the raw
     predicted DEG (internal consistency).
  4. The stage-10 filter+rank output matches the same filter applied to the
     frozen scoring result on identical inputs (the final ranked drug list is
     the parity seam).

The frozen pipeline's CSVs under miri_reposition/xpert-fda-v1_history/CSVs are
STALE artifacts (produced from an earlier DEG/reference state); they are not a
valid parity baseline. The valid baseline is the frozen scoring logic run
against the same inputs the refactored pipeline consumes.

Usage:
    python scripts/verify_parity.py
"""

import json
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from utils import WORKFLOW_ROOT, WORKSPACE_ROOT  # noqa: E402

import scoring  # noqa: E402

HISTORY = WORKSPACE_ROOT / "miri_reposition/xpert-fda-v1_history"
WF = WORKFLOW_ROOT

DEG = WF / "data/deg/xpert_fda-cm_deg.csv"
GENE_SET = WF / "reference-genesets/MIRI_up-down.json"
RANK_REF = WF / "reference-genesets/MIRI_rank.json"
PATHWAYS = WF / "reference-genesets/MIRI_pathways.json"


def check(name, cond, detail=""):
    print(f"  [{'PASS' if cond else 'FAIL'}] {name}" + (f"  ({detail})" if detail else ""))
    return cond


def verify_reference_genesets():
    print("\n1. Reference gene sets regenerated by stage 07")
    ok = True
    for fname in ("MIRI_up-down.json", "MIRI_rank.json"):
        new = json.load(open(WF / "reference-genesets" / fname))
        old = json.load(open(HISTORY / "reference-genesets" / fname))
        if fname == "MIRI_up-down.json":
            same = new["up_genes"] == old["up_genes"] and new["down_genes"] == old["down_genes"]
            ok &= check(f"{fname} gene content identical", same,
                        f"{len(new['up_genes'])} UP + {len(new['down_genes'])} DOWN")
        else:
            ng = [(g["gene"], g["signed_rank"]) for g in new["genes"]]
            og = [(g["gene"], g["signed_rank"]) for g in old["genes"]]
            ok &= check(f"{fname} ranked content identical", ng == og, f"{len(ng)} genes")
    return ok


def _run_frozen_script(script, args):
    """Run a frozen scoring script as a subprocess and load its output CSV."""
    import tempfile
    out = Path(tempfile.mktemp(suffix=".csv"))
    cmd = [sys.executable, str(HISTORY / "scripts" / script), *args,
           "--output", str(out)]
    subprocess.run(cmd, check=True, capture_output=True)
    import pandas as pd
    df = pd.read_csv(out)
    out.unlink()
    return df


def verify_scoring_parity():
    print("\n2. Workflow scoring == frozen scoring logic (same inputs)")
    import pandas as pd

    frozen_wcs = _run_frozen_script("score_wcs_rges.py",
        ["--deg-csv", str(DEG), "--gene-set", str(GENE_SET), "--zscore"])
    frozen_zhang = _run_frozen_script("score_zhang.py",
        ["--deg-csv", str(DEG), "--rank-ref", str(RANK_REF), "--zscore"])
    frozen_pw = _run_frozen_script("score_pathway_rges.py",
        ["--deg-csv", str(DEG), "--pathways", str(PATHWAYS), "--zscore"])

    frozen = frozen_wcs[["drug_name", "WCS", "RGES", "WCS_zs", "RGES_zs"]].merge(
        frozen_zhang[["drug_name", "Zhang_c", "Zhang_zs"]], on="drug_name").merge(
        frozen_pw[["drug_name", "pathway_reversal", "pathway_reversal_zs"]],
        on="drug_name")

    new = scoring.run_scoring(str(DEG), str(GENE_SET), str(RANK_REF),
                              str(PATHWAYS), zscore=True)
    frozen = frozen.set_index("drug_name")
    new = new.set_index("drug_name")
    ok = True
    for col in ["WCS", "RGES", "Zhang_c", "pathway_reversal",
                "WCS_zs", "RGES_zs", "Zhang_zs", "pathway_reversal_zs"]:
        d = np.abs(new.loc[frozen.index, col].values - frozen[col].values).max()
        ok &= check(f"{col} identical", d < 1e-9, f"max diff {d:.2e}")
    return ok


def verify_zscore_consistency():
    print("\n3. Stage 06 z-scored DEG == per-gene z-score of raw DEG")
    import pandas as pd
    raw = pd.read_csv(DEG)
    zs = pd.read_csv(WF / "data/deg-zs/xpert_fda-cm_deg-zs.csv")
    gc = raw.columns[3:].tolist()
    m = raw[gc].values.astype(float)
    mu, sd = m.mean(axis=0), m.std(axis=0)
    sd[sd < 1e-10] = 1.0
    manual = (m - mu) / sd
    d = np.abs(zs[gc].values.astype(float) - manual).max()
    return check("z-scored DEG consistent", d < 1e-9, f"max diff {d:.2e}")


def verify_ranked_output():
    print("\n4. Stage 10 ranked output == frozen scoring filters on same inputs")
    import json
    import pandas as pd

    # Rebuild the scores the way the frozen pipeline produced them (raw DEG +
    # zscore inside scoring), then apply stage 10's filter/rank logic.
    ref = scoring.run_scoring(str(DEG), str(GENE_SET), str(RANK_REF),
                              str(PATHWAYS), zscore=True)
    with open(PATHWAYS) as f:
        critical = [p["name"] for p in json.load(f)["pathways"] if p.get("critical")]

    wcs_pass = ref[ref["WCS"] < 0].copy()
    n_positive = pd.Series(0, index=wcs_pass.index)
    for name in critical:
        n_positive += (wcs_pass[f"{name}_efficacy"] > 0).astype(int)
    expected = wcs_pass[n_positive >= 6].sort_values(
        "integrated", ascending=False)["drug_name"].tolist()

    ranked = pd.read_csv(WF / "data/ranked/ranked_drugs.csv")
    actual = ranked["drug_name"].tolist()
    same = expected == actual
    return check("ranked drug list identical to frozen-pipeline filters",
                 same, f"{len(actual)} drugs")


def main():
    print("=" * 60)
    print("Parity verification: refactored vs frozen pipeline")
    print("=" * 60)
    results = [
        verify_reference_genesets(),
        verify_scoring_parity(),
        verify_zscore_consistency(),
        verify_ranked_output(),
    ]
    print("\n" + "=" * 60)
    print(f"RESULT: {'ALL CHECKS PASSED' if all(results) else 'SOME CHECKS FAILED'}")
    print("=" * 60)
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
