#!/usr/bin/env python3
"""Build the xpert-fda-v1 screen.ipynb orchestrator notebook.

The orchestrator documents and runs the ten numbered workflow stages in
dependency order. It is regenerated by running this script; it is committed to
the repo as the single entry point for executing the MIRI screening pipeline.
"""

import json
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "screen.ipynb"


def md(src):
    return {"cell_type": "markdown", "metadata": {}, "source": src}


def code(src):
    return {"cell_type": "code", "execution_count": None,
            "metadata": {}, "outputs": [], "source": src}


cells = [
    md("# MIRI Drug Repositioning Screen — xpert-fda-v1\n\n"
       "Single orchestrator for the numbered workflow stages (01-10). Run cells in order. "
       "Each stage is independently runnable from `scripts/` and produces its own artifact.\n\n"
       "Environment: `conda activate arc` (see root `environment.yml`). "
       "Heavy stages (02 embeddings, 04 finetune, 05 predict) require a GPU."),

    md("## Stage 01 — Drug list\n\n"
       "Generates the 3,127-drug FDA list from the ChEMBL source table. "
       "Output: `data/drug_list.csv`."),
    code("!python scripts/01_drug_list.py"),

    md("## Stage 02 — Drug embeddings\n\n"
       "Arranges the frozen UniMol array + SMILES mapping and generates the HG "
       "biological embeddings. Idempotent: skips HG inference when an intact "
       "`data/embeddings/all_drugs_idx2HG.npy` exists. "
       "Output: `data/embeddings/`."),
    code("!python scripts/02_drug_embeddings.py\n\n"
         "# Force regeneration:\n# !python scripts/02_drug_embeddings.py --force"),

    md("## Stage 03 — Baseline transcriptome\n\n"
       "Builds the workflow-owned consensus cardiomyocyte baseline from DTOXS "
       "control wells. Output: `data/baseline/cm_ctl_landmark.csv`."),
    code("!python scripts/03_baseline_transcriptome.py"),

    md("## Stage 04 — Finetune XPert on DTOXS\n\n"
       "Runs the dtoxs finetune (workflow-owned weights). "
       "Output: `finetune/output/dtoxs_dtoxs/`."),
    code("!python scripts/04_finetune_xpert.py"),

    md("## Stage 05 — Perturbed transcriptomes\n\n"
       "Predicts drug perturbation (deg) for all FDA drugs via XPert. Predict "
       "indexes the precomputed UniMol array by drug index, so finetune and "
       "predict consume identical features. Output: `data/deg/xpert_fda-cm_deg.csv`."),
    code("!python scripts/05_perturbed_transcriptomes.py"),

    md("## Stage 06 — Z-score\n\n"
       "Z-score normalizes the predicted DEG per gene across drugs. "
       "Output: `data/deg-zs/xpert_fda-cm_deg-zs.csv`."),
    code("!python scripts/06_zscore.py"),

    md("## Stage 07 — Build MIRI reference DEG list\n\n"
       "Consumes the per-GSE DEG lists in `disease_data/miri/{GSE}/deg/` and "
       "produces the integrated reference (`MIRI_up-down.json`, `MIRI_rank.json`)."),
    code("!python scripts/07_build_miri_deg_reference.py"),

    md("## Stage 08 — Efficacy scores\n\n"
       "Runs the three scorers (WCS+RGES, Zhang/ssCMap, pathway RGES) and "
       "computes the four z-components + integrated score. "
       "Output: `data/scores/1-scores.csv`."),
    code("!python scripts/08_efficacy_scores.py"),

    md("## Stage 09 — Reports (gpt-researcher)\n\n"
       "Builds the deterministic report-gating artifacts and prints the prompts "
       "for the gpt-researcher steps (4-regulation, 5_efficacy_reports, "
       "6-reposition_report). The evidence reports require API keys in `.env` and "
       "the gpt-researcher skill; run them via the agent workflow described in "
       "`prompts/` or pass `--run-gptr`."),
    code("!python scripts/09_reports.py"),

    md("## Stage 10 — Filter + rank\n\n"
       "Applies the WCS<0 and critical-pathway filters and produces the final "
       "ranked drug list. Output: `data/ranked/ranked_drugs.csv`."),
    code("!python scripts/10_filter_rank.py"),

    md("## Pipeline summary\n\n"
       "The final ranked drug list is `data/ranked/ranked_drugs.csv`. "
       "For parity checking against the pre-refactor pipeline, compare this "
       "output with the archived result in `miri_reposition/xpert-fda-v1_history/`."),
    code("import pandas as pd\n"
         "ranked = pd.read_csv('data/ranked/ranked_drugs.csv')\n"
         "print(f'{len(ranked)} drugs passed the filters')\n"
         "print(ranked[['drug_name', 'integrated']].head(10).to_string(index=False))"),
]

nb = {
    "cells": cells,
    "metadata": {
        "kernelspec": {"display_name": "arc", "language": "python", "name": "python3"},
        "language_info": {"name": "python", "version": "3.13"},
    },
    "nbformat": 4,
    "nbformat_minor": 5,
}

OUT.write_text(json.dumps(nb, indent=1) + "\n")
print(f"Wrote {OUT}")
