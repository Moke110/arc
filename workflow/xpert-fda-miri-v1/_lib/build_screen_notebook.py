#!/usr/bin/env python3
"""Build the xpert-fda-miri-v1 screen.ipynb orchestrator notebook.

xpert-fda-miri-v1 is the finalized author-aligned L1000-contained FDA screen:
only the FDA drugs whose exact canonical SMILES match the L1000 embedding table
(drug_idx < 8981) are screened, so step 01 uses the author-reference HG
embedding directly and never trains/fine-tunes the HG model. The step layout is
the 11-step one shared with xpert-fda-miri-v1.1/v2/v3 (01_drug_embed …
11_integrate, with 03_cm_finetune_data owning the frozen DToxS finetune data).
The agentic bilingual report is archived as a non-numbered `report/` stage.
Regenerated by running this script.
"""

import json
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "screen.ipynb"


def md(src):
    return {"cell_type": "markdown", "metadata": {}, "source": src}


def code(src):
    return {"cell_type": "code", "execution_count": None,
            "metadata": {}, "outputs": [], "source": src}


cells = [
    md("# MIRI Drug Repositioning Screen — xpert-fda-miri-v1\n\n"
       "Finalized, author-aligned, L1000-contained FDA screen. Only FDA drugs "
       "present in the L1000 embedding table (exact SMILES match, drug_idx < "
       "8981) are screened; the HG biological embeddings are the **author "
       "reference table** — no HG training / FDA-extension inference. Run cells "
       "in order. Environment: `conda activate arc`. Heavy steps (05 benchmark, "
       "06 finetune, 07 predict) require a GPU."),

    md("## Step 01 — Drug list + embeddings\n\n"
       "Filters the ChEMBL FDA table (`input/fda_drugs.csv`) to drugs whose "
       "exact canonical SMILES is in the L1000 rows of the embedding mapping "
       "(`drug_idx < 8981`), then copies the author reference HG table "
       "(workflow-owned `input/HG_drug_embeddings.npy`) to "
       "`01_drug_embed/output/all_drugs_idx2HG.npy` (byte-identical parity "
       "gate). Outputs: `01_drug_embed/output/drug_list.csv` (1,004 drugs) + "
       "`all_drugs_idx2HG.npy`."),
    code("!python 01_drug_embed/drug_list.py\n"
         "!python 01_drug_embed/drug_embeddings.py"),

    md("## Gene mapping — authoritative DTOXS -> L1000 + verification\n\n"
       "Builds the Entrez-verified DToxS->L1000 landmark gene map (resolves the "
       "18 legacy-symbol landmarks such as WASHC5<-KIAA0196, JPT2<-HN1L) and "
       "gates that all 978 landmarks participate in the finetune. "
       "Run before step 02."),
    code("!python _lib/verify_genes.py"),

    md("## Step 02 — CM baseline transcriptome\n\n"
       "Builds the consensus cardiomyocyte baseline from DTOXS control wells "
       "using the authoritative gene map (no lost legacy-symbol genes). "
       "Output: `02_cm_baseline/output/cm_ctl_landmark.csv`."),
    code("!python 02_cm_baseline/cm_baseline.py"),

    md("## Step 03 — DToxS finetune data (workflow-owned, frozen)\n\n"
       "Owns the frozen DToxS finetune h5ad (`03_cm_finetune_data/output/"
       "dtoxs.h5ad`, 521 samples / 36 drugs), moved here from "
       "`pert_data/dtoxs_primary/v1-frozen/` so the workflow is self-contained "
       "on its finetune data (like the v1.1/v2/v3 step-03 data prep). Not "
       "rebuilt; its fold columns are regenerated in place by step 05."),
    code("!ls 03_cm_finetune_data/output/"),

    md("## Step 04 — XPert pretrain (reference, workflow-owned)\n\n"
       "Holds the author pretrained XPert base weight (`pretrain_mdmt_full_50_"
       "epoch.pth`) and the L1000 pretrain YAML that produced it — the pretrain "
       "dataset lives under `pert_data/l1000-xpert/`. Not re-run during "
       "screening; steps 05/06 consume the weight from here."),
    code("!ls 04_xpert_pretrain/"),

    md("## Step 05 — Benchmark XPert on DTOXS splits\n\n"
       "Regenerates the unified fold columns (warm-start + cold-drug, 10 folds "
       "each, ADR 0014) on the frozen `03_cm_finetune_data/output/dtoxs.h5ad`, "
       "then finetunes and benchmarks each fold on its held-out test set "
       "(weights kept). The L1000 pretrain weight is also evaluated zero-shot "
       "(no finetuning) on all 20 fold test sets and plotted as the FIRST "
       "column (`pretrain`, amber). Per-fold values are overlaid as black dots "
       "on the mean ± std bars. Side branch: downstream steps use the step-06 "
       "model. Outputs: `05_xpert_finetune_bench/output/benchmark.csv` + "
       "`benchmark.png`."),
    code("!python 05_xpert_finetune_bench/create_dtoxs_splits.py\n"
         "!python 05_xpert_finetune_bench/xpert_finetune_bench.py"),

    md("## Step 06 — Finetune XPert on DTOXS\n\n"
       "Full-DToxS finetune -> the final prediction model (base weight from "
       "step 04). Idempotent (weights kept). Output: "
       "`06_xpert_finetune/output/dtoxs_dtoxs/`."),
    code("!python 06_xpert_finetune/xpert_finetune.py"),

    md("## Step 07 — Perturbed transcriptome + z-score\n\n"
       "Predicts drug perturbation (deg) for the 1,004 L1000-contained FDA "
       "drugs via XPert (step-06 model), then z-score normalizes the DEG per "
       "gene across drugs. Predict indexes the precomputed UniMol array by drug "
       "index, so finetune and predict consume identical features. Outputs: "
       "`07_xpert_predict/output/xpert_fda-cm_deg.csv` + `-zs.csv`."),
    code("!python 07_xpert_predict/perturb_transcriptome.py\n"
         "!python 07_xpert_predict/zscore.py"),

    md("## Step 08 — MIRI reference gene sets + pathways\n\n"
       "Consumes the per-GSE DEG lists in `disease_data/miri/{GSE}/deg/` and "
       "produces the integrated reference (`MIRI_up-down.json`, "
       "`MIRI_rank.json`). `input/MIRI_pathways.json` is static (curated)."),
    code("!python 08_miri_phenotype/miri_phenotype.py"),

    md("## Step 09 — Efficacy scores\n\n"
       "Runs the three scorers (WCS+RGES, Zhang/ssCMap, pathway RGES) and "
       "computes the z-components for all screened drugs, plus the "
       "score-distribution plots. Output: `09_miri_efficacy_scores/output/"
       "scores.csv` + PNGs."),
    code("!python 09_miri_efficacy_scores/miri_efficacy_scores.py"),

    md("## Step 10 — Filter\n\n"
       "Applies the WCS<0 and >=6/8 critical-pathway filters + filter-"
       "progression pyramid plot. Outputs: `10_filter/output/wcs_filtered.csv`, "
       "`path_filtered.csv`, `pyramid-filters.png`."),
    code("!python 10_filter/filter.py"),

    md("## Step 11 — Integrate\n\n"
       "Computes the integrated score over all screened drugs, ranks the "
       "filtered candidates, and writes the final report: "
       "`11_integrate/output/integrated_scores.csv`, `ranked_drugs.csv`, "
       "`report.md` + rank heatmaps."),
    code("!python 11_integrate/integrate.py"),

    md("## Archived report stage (not a numbered step)\n\n"
       "The agentic bilingual per-drug report (`report/`) is archived as a "
       "non-numbered stage to keep the numbered steps identical to "
       "xpert-fda-miri-v1.1/v2/v3. Run `report/run_drug_agents.py` + "
       "`report/assemble_report.py` + `report/assemble_cn_report.py` over the "
       "`10_filter` survivors with integrated percentile > 0.5."),
    code("!ls report/"),

    md("## Pipeline summary\n\n"
       "The final ranked drug list is `11_integrate/output/ranked_drugs.csv` "
       "with the deterministic report at `11_integrate/output/report.md` and "
       "the archived agentic drug report at `report/output/report.md`."),
    code("import pandas as pd\n"
         "ranked = pd.read_csv('11_integrate/output/ranked_drugs.csv')\n"
         "print(f'{len(ranked)} drugs passed the filters')\n"
         "print(ranked[['drug_name', 'integrated']].head(10).to_string(index=False))"),
]

nb = {
    "cells": cells,
    "metadata": {
        "kernelspec": {"display_name": "arc", "language": "python", "name": "python3"},
        "language_info": {"name": "python", "version": "3.13"},
    },
    "nbformat": 4,
    "nbformat_minor": 5,
}

OUT.write_text(json.dumps(nb, indent=1) + "\n")
print(f"Wrote {OUT}")
