"""
Gene-identity mapping and the common whole-transcriptome gene universe.

Each CM dataset identifies genes in its own space (`dtoxs_primary`/`dtoxs_ipsc`:
HGNC symbols; `gse244740`: Ensembl gene IDs). Everything is mapped to HGNC
symbols — the common currency — using the bundled Ensembl->symbol map
(`input/ensembl_to_symbol.tsv`, generated by `fetch_gene_symbol_map.py`).

The **common gene universe** is the intersection of the participating
datasets' mapped symbol sets, sorted deterministically. It is persisted so it is
byte-stable on re-run, and every true set and AUPRC is computed inside it.
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from utils import INPUT_DIR  # noqa: E402


def load_ensembl_map():
    df = pd.read_csv(INPUT_DIR / "ensembl_to_symbol.tsv", sep="\t",
                     keep_default_na=False)
    return {str(r["ensembl_id"]): str(r["gene_symbol"]) for _, r in df.iterrows()
            if str(r["gene_symbol"])}


def _symbols_for(space, gene_ids, ensembl_map):
    out = []
    for g in gene_ids:
        g = str(g).strip()
        if not g:
            out.append("")
            continue
        if space == "ensembl":
            out.append(ensembl_map.get(g.split(".")[0], ""))
        else:
            out.append(g.split(".")[0])
    return out


def collapse_to_symbols(counts, gene_ids, space, ensembl_map):
    """Sum counts of native rows that share a symbol.

    Returns (symbols sorted, matrix (n_samples, n_symbols), stats dict).
    Rows with no resolvable symbol are dropped and counted.
    """
    syms = _symbols_for(space, gene_ids, ensembl_map)
    groups = {}
    unmapped = 0
    for i, s in enumerate(syms):
        if not s:
            unmapped += 1
            continue
        groups.setdefault(s, []).append(i)
    symbols = sorted(groups)
    mat = np.zeros((counts.shape[0], len(symbols)), dtype=float)
    for j, s in enumerate(symbols):
        mat[:, j] = counts[:, groups[s]].sum(axis=1)
    stats = {"n_native": len(gene_ids), "n_mapped": len(symbols),
             "n_unmapped": unmapped, "n_duplicate_symbols":
                 sum(1 for s in groups if len(groups[s]) > 1)}
    return symbols, mat, stats


def common_universe(symbol_sets):
    """Deterministic intersection of per-dataset symbol sets."""
    universe = set.intersection(*[set(s) for s in symbol_sets.values()])
    return sorted(universe)


def align_matrix(symbols, matrix, universe):
    """Subset/reorder a (n_samples, n_symbols) matrix to the universe order."""
    index = {s: j for j, s in enumerate(symbols)}
    cols = [index[s] for s in universe]
    return matrix[:, cols]
